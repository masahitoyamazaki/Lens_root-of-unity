# used for draft Sec. "Symmetries and general torsion points", paragraph "Classification of the orbits"
"""Orbits of primitive n-torsion points omega0 = pi(kappa MT - nu)/n, encoded as (X,Y)=(-nu, kappa),
under the symmetries (a)-(c) of (KMnssr).  X is taken modulo nh (nh = 2n if n and M are both even, nh = n otherwise),
Y modulo n; the linear part is generated by -1 and by h=[[a,b],[c,d]] in SL(2,Z) with a=d=1 mod 2M, b=0 mod M, c=0 mod 2
(h = [[alpha, -beta M],[-gamma/M, delta]] in terms of (c)).
Checks the predictions: transitive iff gcd(n,2M)=1; QF orbit = {nu = +-1 mod D, kappa even if n even},
D = gcd(n,M) (n odd), 2 gcd(n,M) (n even).  Derived (real) points: (kappa,nu)=(k,kr), gcd(k,n)=1, r|M."""
from math import gcd

def gens(n, M):
    G = []
    for a in range(1 - 4*M, 4*M + 2, 2*M):
        for c in range(-4*M, 4*M + 1, 2*M):      # c here is gamma; the matrix entry is -gamma/M
            for b in range(-6, 7):                 # b here is beta; the matrix entry is -beta M
                num = 1 + b*c
                if num % a == 0:
                    G.append((a, b, c, num // a))
    return G

def nhat(n, M):
    return n if (n % 2 or M % 2) else 2*n

def orbits(n, M):
    nh = nhat(n, M)
    pts = [(X, Y) for X in range(nh) for Y in range(n) if gcd(gcd(X, Y), n) == 1]
    G = gens(n, M); seen = set(); orbs = []
    for p in pts:
        if p in seen: continue
        orb = {p}; st = [p]
        while st:
            X, Y = st.pop()
            cand = [((-X) % nh, (-Y) % n)]
            for a, b, c, d in G:
                cand.append(((a*X - b*M*Y) % nh, (-(c//M)*X + d*Y) % n))
            for r in cand:
                if r not in orb: orb.add(r); st.append(r)
        seen |= orb; orbs.append(orb)
    return nh, orbs

def predicted_QF(n, M):
    nh = nhat(n, M); g = gcd(n, M); D = g if n % 2 else 2*g
    return {(X, Y) for X in range(nh) for Y in range(n) if gcd(gcd(X, Y), n) == 1
            and (n % 2 or Y % 2 == 0) and ((X - 1) % D == 0 or (X + 1) % D == 0)}

def real_points(n, M):
    nh = nhat(n, M)
    return {((-k*r) % nh, k % n) for k in range(1, n) if gcd(k, n) == 1 for r in range(1, M+1) if M % r == 0}

def coverage(n, M):
    """points (as (kappa,nu)) related neither to the QF point nor to a real point (k,kr)."""
    nh, orbs = orbits(n, M); real = real_points(n, M)
    unc = set().union(*[o for o in orbs if not (o & real) and (1 % nh, 0) not in o]) if orbs else set()
    return sorted((Y, (-X) % nh) for X, Y in unc)

if __name__ == '__main__':
    bad = []
    for n in range(2, 11):
        for M in range(1, 11):
            nh, orbs = orbits(n, M)
            qf = [o for o in orbs if (1 % nh, 0) in o][0]
            ok_qf = (qf == predicted_QF(n, M))
            ok_tr = ((len(orbs) == 1) == (gcd(n, 2*M) == 1))
            unc = coverage(n, M)
            print(f"n={n} M={M} nh={nh} orbits={len(orbs)} QF-orbit-as-predicted={ok_qf} transitivity-as-predicted={ok_tr} uncovered={len(unc)}")
            if not (ok_qf and ok_tr): bad.append((n, M))
    print("mismatches:", bad)
